/** Glyph for one character; unknown characters render as a space. */
export function glyph(ch: string): readonly string[] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS[" "];
}

/** Lay out a word as one bitmap, with a one-pixel gap between characters. */
export function textToRows(text: string): string[] {
  const rows: string[] = Array.from({ length: GLYPH_HEIGHT }, () => "");
  [...text].forEach((ch, i) => {
    glyph(ch).forEach((row, r) => {
      rows[r] += (i ? "." : "") + row;
    });
  });
  return rows;
}
